def discover_llm4vkg_metrics(llm4vkg_root: Path, output_root: Path) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    for f1_path in sorted((llm4vkg_root / "outputs").glob("**/f1.txt")):
        scenario = f1_path.parent.name
        f1 = None
        precision = None
        recall = None
        for line in f1_path.read_text(encoding="utf-8", errors="replace").splitlines():
            if "Average Precision" in line:
                precision = _last_float(line)
            elif "Average Recall" in line:
                recall = _last_float(line)
            elif "Average F1" in line:
                f1 = _last_float(line)
        rows.append({"scenario": scenario, "precision": precision, "recall": recall, "f1": f1, "path": str(f1_path)})
    ensure_dir(output_root)
    with (output_root / "llm4vkg_metrics.csv").open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=["scenario", "precision", "recall", "f1", "path"])
        writer.writeheader()
        writer.writerows(rows)
    return rows


def _last_float(line: str) -> float | None:
    for token in reversed(line.replace(":", " ").split()):
        try:
            return float(token)
        except ValueError:
            continue
    return None


def bootstrap_llm4vkg(
    llm4vkg_root: Path,
    devset_root: Path,
    output_root: Path,
    scenarios: Sequence[str],
    api_names: Sequence[str],
    db_host: str,
    db_port: int,
    db_user: str,
    db_password: str,
    db_name: str,
    run_generation: bool,
    run_evaluation: bool,
    dry_run_db: bool = False,
    java_home: Path | None = None,
    db_loader: str = "psql",
    compose_root: Path | None = None,
    lightweight_retriever: bool = False,
) -> dict[str, object]:
    ensure_dir(output_root)
    status = check_llm4vkg_resources(llm4vkg_root)
    config_path = write_llm4vkg_config(llm4vkg_root, api_names=api_names, db_host=db_host, db_port=db_port, db_user=db_user, db_password=db_password)
    dataset_path = sync_llm4vkg_devset(devset_root, llm4vkg_root, scenarios)
    db_results = load_postgres_dumps(
        devset_root,
        scenarios,
        db_host,
        db_port,
        db_user,
        db_password,
        db_name,
        dry_run=dry_run_db,
        loader=db_loader,
        compose_root=compose_root,
    )
    command_results: list[dict[str, object]] = []
    if status.ok and not dry_run_db:
        command_results = run_llm4vkg_commands(
            llm4vkg_root,
            scenarios=scenarios,
            api_names=api_names,
            run_generation=run_generation,
            run_evaluation=run_evaluation,
            java_home=java_home,
            lightweight_retriever=lightweight_retriever,
        )
    metrics = discover_llm4vkg_metrics(llm4vkg_root, output_root)
    result = {
        "status": status.to_jsonable(),
        "config_path": str(config_path),
        "dataset_path": str(dataset_path),
        "db_results": db_results,
        "command_results": command_results,
        "metrics": metrics,
    }
    write_json(output_root / "llm4vkg_run.json", result)
    return result
