def configure_lightweight_retriever() -> None:
    import src.vkg_generation.ontology_completion_mapping_generation as oc_module

    original_sentence_transformer = oc_module.SentenceTransformer
    if not LIGHTWEIGHT_RETRIEVER:
        class CpuSentenceTransformer(original_sentence_transformer):
            def __init__(self, model_name_or_path=None, *args, **kwargs):
                if kwargs.get("device") == "cuda":
                    kwargs["device"] = "cpu"
                super().__init__(model_name_or_path, *args, **kwargs)

        oc_module.SentenceTransformer = CpuSentenceTransformer
        return

    import hashlib
    import torch

    class LightweightSentenceTransformer:
        def __init__(self, *args, **kwargs):
            self.dim = 256

        def encode(self, texts, convert_to_tensor=False):
            vectors = []
            for text in texts:
                vec = torch.zeros(self.dim)
                for token in str(text).lower().split() or [str(text)]:
                    digest = hashlib.sha256(token.encode("utf-8")).digest()
                    idx = int.from_bytes(digest[:4], "big") % self.dim
                    vec[idx] += 1.0 if digest[4] % 2 == 0 else -1.0
                norm = torch.linalg.vector_norm(vec)
                if norm.item() > 0:
                    vec = vec / norm
                vectors.append(vec)
            tensor = torch.stack(vectors) if vectors else torch.empty((0, self.dim))
            return tensor if convert_to_tensor else tensor.numpy()

    oc_module.SentenceTransformer = LightweightSentenceTransformer

