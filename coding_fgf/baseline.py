@dataclass(frozen=True)
class BaselineCheck:
    name: str
    ok: bool
    detail: str


@dataclass
class BaselineStatus:
    llm4vkg_root: Path
    checks: list[BaselineCheck] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return all(check.ok for check in self.checks)

    def to_jsonable(self) -> dict[str, object]:
        return {
            "llm4vkg_root": str(self.llm4vkg_root),
            "ok": self.ok,
            "checks": [check.__dict__ for check in self.checks],
        }


def default_llm4vkg_root(rodi_root: Path) -> Path:
    return rodi_root / "tools" / "LLM4VKG" / "LLM4VKG"


def check_llm4vkg_resources(llm4vkg_root: Path, require_logmap: bool = False) -> BaselineStatus:
    checks = [
        BaselineCheck("root", llm4vkg_root.exists(), str(llm4vkg_root)),
        BaselineCheck("pyproject", (llm4vkg_root / "pyproject.toml").exists(), "pyproject.toml"),
        BaselineCheck("uv", shutil.which("uv") is not None, shutil.which("uv") or "uv not on PATH"),
        BaselineCheck("ontop", _ontop_exists(llm4vkg_root), "resources/ontop/ontop"),
    ]
    if require_logmap:
        checks.append(
            BaselineCheck(
                "logmap",
                bool(list((llm4vkg_root / "resources" / "logmap").glob("**/*logmap*.jar"))),
                "resources/logmap/**/*logmap*.jar",
            )
        )
    return BaselineStatus(llm4vkg_root=llm4vkg_root, checks=checks)


def _ontop_exists(llm4vkg_root: Path) -> bool:
    candidates = [
        llm4vkg_root / "resources" / "ontop" / "ontop",
        llm4vkg_root / "resources" / "ontop" / "ontop.bat",
        llm4vkg_root / "resources" / "ontop" / "bin" / "ontop",
        llm4vkg_root / "resources" / "ontop" / "bin" / "ontop.bat",
    ]
    return any(path.exists() for path in candidates)


