def sync_llm4vkg_devset(devset_root: Path, llm4vkg_root: Path, scenarios: Sequence[str]) -> Path:
    target = llm4vkg_root / "datasets" / "rodi"
    ensure_dir(target)
    for scenario in scenarios:
        src = devset_root / scenario
        dst = target / scenario
        if not src.exists():
            raise FileNotFoundError(f"Missing devset scenario {src}")
        if dst.exists():
            shutil.rmtree(dst)
        shutil.copytree(src, dst)
    return target


