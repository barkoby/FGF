def java_env(java_home: Path | None = None) -> dict[str, str]:
    env = os.environ.copy()
    env["PYTHONIOENCODING"] = "utf-8"
    env["PYTHONUTF8"] = "1"
    if java_home:
        env["JAVA_HOME"] = str(java_home)
        env["PATH"] = str(java_home / "bin") + os.pathsep + env.get("PATH", "")
    return env


def run_llm4vkg_commands(
    llm4vkg_root: Path,
    scenarios: Sequence[str],
    api_names: Sequence[str],
    run_generation: bool,
    run_evaluation: bool,
    java_home: Path | None = None,
    lightweight_retriever: bool = False,
) -> list[dict[str, object]]:
    commands: list[list[str]] = []
    if run_generation or run_evaluation:
        if os.getenv("CODING_FGF_CPU_TORCH") == "1":
            commands.extend([["uv", "sync"], ["uv", "pip", "install", *_uv_python_args(), "psycopg2-binary"]])
        else:
            commands.extend([["uv", "sync"], ["uv", "pip", "install", "psycopg2-binary"]])
    if run_generation:
        runner = write_filtered_runner(llm4vkg_root, scenarios, lightweight_retriever=lightweight_retriever)
        commands.append(["uv", "run", "python", str(runner.name)])
    if run_evaluation:
        eval_paths = [str(Path("outputs") / "rodi" / f"LLM4VKG_{api}") for api in api_names]
        eval_runner = write_eval_runner(llm4vkg_root, scenarios=scenarios, eval_paths=eval_paths)
        commands.append(["uv", "run", "python", str(eval_runner.name)])
    results: list[dict[str, object]] = []
    env = java_env(java_home)
    for command in commands:
        result = run_command(command, cwd=llm4vkg_root, env=env, timeout=3600)
        results.append(result)
        if result["returncode"] != 0:
            break
    return results


def _uv_python_args() -> list[str]:
    env_path = os.getenv("UV_PROJECT_ENVIRONMENT")
    if not env_path:
        return []
    executable = Path(env_path) / ("Scripts/python.exe" if os.name == "nt" else "bin/python")
    return ["--python", str(executable)]


def run_command(
    command: Sequence[str],
    cwd: Path,
    env: dict[str, str] | None = None,
    input_text: str | None = None,
    timeout: int = 300,
) -> dict[str, object]:
    proc = subprocess.run(
        list(command),
        cwd=cwd,
        env=env,
        input=None if input_text is None else input_text.encode("utf-8"),
        capture_output=True,
        timeout=timeout,
    )
    stdout = (proc.stdout or b"").decode("utf-8", errors="replace")
    stderr = (proc.stderr or b"").decode("utf-8", errors="replace")
    return {"command": list(command), "returncode": proc.returncode, "stdout": stdout[-4000:], "stderr": stderr[-4000:]}


